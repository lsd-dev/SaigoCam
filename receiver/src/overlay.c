static const unsigned char *find_glyph(char c)
{
    size_t i;
    c = (char)toupper((unsigned char)c);
    for (i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
        if (glyphs[i].c == c)
            return glyphs[i].rows;
    return NULL; /* space and anything unknown */
}

/* Rectangles are batched so a full overlay is a handful of draw calls. */
#define BATCH 512
static SDL_Rect batch[BATCH];
static int batch_n;

static void batch_flush(SDL_Renderer *ren)
{
    if (batch_n) {
        SDL_RenderFillRects(ren, batch, batch_n);
        batch_n = 0;
    }
}

static void batch_add(SDL_Renderer *ren, int x, int y, int w, int h)
{
    if (batch_n == BATCH)
        batch_flush(ren);
    batch[batch_n].x = x;
    batch[batch_n].y = y;
    batch[batch_n].w = w;
    batch[batch_n].h = h;
    batch_n++;
}

void overlay_draw(SDL_Renderer *ren, int x, int y, int scale,
                  const char *const *lines, int n_lines)
{
    int i, max_len = 0, pad = 3 * scale;
    SDL_Rect bg;

    if (n_lines <= 0)
        return;
    for (i = 0; i < n_lines; i++) {
        int len = (int)strlen(lines[i]);
        if (len > max_len)
            max_len = len;
    }

    bg.x = x;
    bg.y = y;
    bg.w = max_len * CELL_W * scale + 2 * pad - scale;
    bg.h = n_lines * CELL_H * scale + 2 * pad - 2 * scale;
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(ren, 0, 0, 0, 170);
    SDL_RenderFillRect(ren, &bg);

    SDL_SetRenderDrawColor(ren, 255, 255, 255, 255);
    for (i = 0; i < n_lines; i++) {
        const char *s = lines[i];
        int col, cy = y + pad + i * CELL_H * scale;
        for (col = 0; s[col]; col++) {
            const unsigned char *g = find_glyph(s[col]);
            int r, b, cx = x + pad + col * CELL_W * scale;
            if (!g)
                continue;
            for (r = 0; r < GLYPH_H; r++)
                for (b = 0; b < GLYPH_W; b++)
                    if (g[r] & (0x10 >> b))
                        batch_add(ren, cx + b * scale, cy + r * scale, scale, scale);
        }
    }
    batch_flush(ren);
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_NONE);
}
